// Scopes the website's global stylesheets under #desk-debate so they cannot
// restyle the desktop workspace. Run after copying website CSS into src/web/styles.
// Usage: node scripts/scope-web-css.mjs
import fs from 'fs';
import path from 'path';

const SCOPE = '#desk-debate';
const SRC_DIR = path.resolve('src/web/styles');
const OUT_DIR = path.resolve('src/web/styles/scoped');
const FILES = ['base.css', 'auth.css', 'debate.css', 'moot.css', 'prep.css'];
// Page-layout declarations of body/html must not reach the desktop pane.
const LAYOUT_PROP = /^(display|grid-template|min-height|height)\b/;

function scopeSelector(sel) {
  const s = sel.trim();
  if (!s) return s;
  if (s === 'html' || s === 'body' || s === ':root') return SCOPE;
  if (/^(body|html)[.#:\[]/.test(s)) return SCOPE + s.replace(/^(body|html)/, '');
  if (s.startsWith(SCOPE)) return s;
  return `${SCOPE} ${s}`;
}

// Splits "a, b" at top-level commas (ignores commas inside parentheses).
function splitSelectors(list) {
  const out = [];
  let depth = 0;
  let cur = '';
  for (const ch of list) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) { out.push(cur); cur = ''; } else cur += ch;
  }
  if (cur.trim()) out.push(cur);
  return out;
}

function scope(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let i = 0;
  let out = '';
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const prelude = css.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    while (j < css.length && depth > 0) {
      if (css[j] === '{') depth++;
      else if (css[j] === '}') depth--;
      j++;
    }
    const body = css.slice(open + 1, j - 1);
    if (/^(body|html)$/.test(prelude)) {
      const kept = body.split(';').map((d) => d.trim()).filter((d) => d && !LAYOUT_PROP.test(d));
      out += `${SCOPE} {\n  ${kept.join(';\n  ')};\n}\n`;
    } else if (prelude.startsWith('@media') || prelude.startsWith('@supports')) {
      out += `${prelude} {\n${scope(body)}}\n`;
    } else if (prelude.startsWith('@')) {
      out += `${prelude} {${body}}\n`;
    } else if (prelude) {
      const sels = splitSelectors(prelude).map(scopeSelector).join(', ');
      out += `${sels} {${body}}\n`;
    }
    i = j;
  }
  return out;
}

fs.mkdirSync(OUT_DIR, { recursive: true });
for (const f of FILES) {
  const src = fs.readFileSync(path.join(SRC_DIR, f), 'utf8');
  const scoped = `/* Generated by scripts/scope-web-css.mjs from src/web/styles/${f}. Do not edit by hand. */\n` + scope(src);
  fs.writeFileSync(path.join(OUT_DIR, f), scoped);
  console.log('scoped', f, scoped.split('\n').length, 'lines');
}
